def _row_features(row):
    frp = max(_safe_float(row.get("max_frp")), 0.0)
    avg_frp = max(_safe_float(row.get("average_frp")), 0.0)
    bt = max(_safe_float(row.get("max_bright_ti4")), 0.0)
    avg_bt = max(_safe_float(row.get("average_bright_ti4")), 0.0)
    count = max(_safe_float(row.get("detection_count")), 0.0)
    duration = max(_safe_float(row.get("observation_duration_minutes")), 0.0)
    distance = max(_safe_float(row.get("facility_distance"), 999999.0), 0.0)
    f1 = max(_safe_float(row.get("facilities_within_1km")), 0.0)
    f5 = max(_safe_float(row.get("facilities_within_5km")), 0.0)
    inside = 1.0 if bool(row.get("inside_industrial")) else 0.0
    land = LAND_COVER_CODE.get(str(row.get("land_cover_class") or "UNKNOWN").upper(), 0)
    land_conf = _safe_float(row.get("land_cover_confidence"))
    facility_text = _norm_text(row.get("facility_type"), row.get("industrial_type"))
    hydro = 1.0 if _contains(facility_text, HYDROCARBON_TERMS) else 0.0
    industrial = 1.0 if _contains(facility_text, INDUSTRIAL_TERMS) else 0.0
    agriculture = 1.0 if _contains(facility_text, AGRICULTURE_TERMS) else 0.0

    dt = row.get("first_detected_at")
    hour = float(getattr(dt, "hour", 12))
    month = float(getattr(dt, "month", 1))
    hour_angle = 2 * math.pi * hour / 24.0
    month_angle = 2 * math.pi * month / 12.0

    return [
        math.log1p(frp),
        math.log1p(avg_frp),
        bt,
        avg_bt,
        math.log1p(count),
        math.log1p(duration),
        math.log1p(distance),
        math.log1p(f1),
        math.log1p(f5),
        inside,
        float(land),
        land_conf,
        hydro,
        industrial,
        agriculture,
        frp / max(count, 1.0),
        math.sin(hour_angle),
        math.cos(hour_angle),
        math.sin(month_angle),
        math.cos(month_angle),
        _safe_float(row.get("latitude")),
        _safe_float(row.get("longitude")),
    ]


def _weak_label(row):
    """Generate the existing evidence-based bootstrap label.

    This deliberately mirrors the project's context-first philosophy.
    """
    frp = _safe_float(row.get("max_frp"))
    bt = _safe_float(row.get("max_bright_ti4"))
    duration = _safe_float(row.get("observation_duration_minutes"))
    count = _safe_int(row.get("detection_count"))
    distance = _safe_float(row.get("facility_distance"), 999999.0)
    inside = bool(row.get("inside_industrial"))
    f1 = _safe_int(row.get("facilities_within_1km"))
    f5 = _safe_int(row.get("facilities_within_5km"))
    land = str(row.get("land_cover_class") or "UNKNOWN").upper()
    land_conf = _safe_float(row.get("land_cover_confidence"))
    facility_text = _norm_text(row.get("facility_type"), row.get("industrial_type"))

    thermal = 0.0
    if frp >= 50: thermal = 1.0
    elif frp >= 20: thermal = 0.75
    elif frp >= 5: thermal = 0.50
    elif frp > 0: thermal = 0.25
    if bt >= 340: thermal = max(thermal, 1.0)
    elif bt >= 330: thermal = max(thermal, 0.75)
    elif bt >= 315: thermal = max(thermal, 0.50)

    persistence = min((duration / 120.0) * 0.7 + min(count / 5.0, 1.0) * 0.3, 1.0)

    industrial = 0.0
    if inside: industrial += .55
    if distance <= 500: industrial += .30
    elif distance <= 1000: industrial += .25
    elif distance <= 3000: industrial += .18
    elif distance <= 5000: industrial += .12
    elif distance <= 10000: industrial += .05
    if f1 >= 5: industrial += .15
    elif f1 >= 2: industrial += .10
    elif f1 >= 1: industrial += .05
    if f5 >= 10: industrial += .05
    if _contains(facility_text, INDUSTRIAL_TERMS): industrial += .08
    industrial = min(industrial, 1.0)

    hydro = _contains(facility_text, HYDROCARBON_TERMS)
    flare = min(1.0, industrial * .75 + (.25 if hydro and distance <= 3000 else 0.0))
    vegetation = land_conf if land in {
        "TREE_COVER", "SHRUBLAND", "GRASSLAND", "HERBACEOUS_WETLAND",
        "MANGROVES", "MOSS_LICHEN",
    } else 0.0
    agriculture = land_conf if land == "CROPLAND" else 0.0
    persistent = min(
        (duration / 180.0) * .65 + min(count / 5.0, 1.0) * .35,
        1.0,
    )

    scores = {
        "INDUSTRIAL FIRE": .10 + 1.0 * industrial + .25 * thermal + .15 * persistence,
        "GAS FLARE / INDUSTRIAL THERMAL SOURCE": .05 + 1.1 * flare + .20 * thermal + .25 * persistence,
        "FOREST / VEGETATION FIRE": .05 + .95 * vegetation + .45 * persistence + .25 * thermal - .65 * industrial,
        "AGRICULTURAL BURNING": .05 + 1.0 * agriculture + .30 * thermal + .20 * persistence - .65 * industrial,
        "PERSISTENT THERMAL SOURCE": .05 + .85 * persistent + .20 * thermal + .15 * industrial,
        "OTHER THERMAL SOURCE": .20 + .55 * (1 - max(industrial, vegetation, agriculture)),
    }
    if not hydro or distance > 5000:
        scores["GAS FLARE / INDUSTRIAL THERMAL SOURCE"] -= .70
    if industrial < .25:
        scores["INDUSTRIAL FIRE"] -= .50
    if land == "UNKNOWN" and industrial < .25:
        scores["OTHER THERMAL SOURCE"] += .35

    label = max(scores, key=scores.get)
    ordered = sorted(scores.values(), reverse=True)
    margin = ordered[0] - ordered[1] if len(ordered) > 1 else ordered[0]
    # Weak-label confidence is used only to filter noisy training rows.
    confidence = max(0.0, min(1.0, 0.45 + 0.40 * margin + 0.20 * ordered[0]))
    return label, confidence



def _load_external_flare_tree():
    """Load public NASA/ORNL VIIRS Nightfire flare-site coordinates if present."""
    files = sorted(EXTERNAL_FLARE_DIR.rglob("*flare_list.csv"))
    if not files:
        return None
    points = []
    for path in files:
        try:
            import pandas as pd
            frame = pd.read_csv(path)
            if "latitude" not in frame or "longitude" not in frame:
                continue
            for lat, lon in zip(frame["latitude"], frame["longitude"]):
                lat = _safe_float(lat, float("nan"))
                lon = _safe_float(lon, float("nan"))
                if math.isfinite(lat) and math.isfinite(lon):
                    points.append((math.radians(lat), math.radians(lon)))
        except Exception as exc:
            logger.warning("Could not read flare dataset %s: %s", path, exc)
    if not points:
        return None
    # Deduplicate to keep the tree compact.
    points = np.unique(np.asarray(points, dtype=np.float64), axis=0)
    return BallTree(points, metric="haversine")


def _is_known_flare(row, flare_tree):
    if flare_tree is None:
        return False
    lat = _safe_float(row.get("latitude"), float("nan"))
    lon = _safe_float(row.get("longitude"), float("nan"))
    if not math.isfinite(lat) or not math.isfinite(lon):
        return False
    query = np.asarray([[math.radians(lat), math.radians(lon)]], dtype=np.float64)
    dist, _ = flare_tree.query(query, k=1)
    return float(dist[0, 0]) * 6371000.0 <= 2000.0

def _load_manual_labels():
    if not LABELS_PATH.exists():
        return {}
    result = {}
    try:
        with LABELS_PATH.open(newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                event_id = row.get("event_id")
                label = str(row.get("label") or "").strip().upper()
                if event_id and label in CLASSES:
                    result[int(event_id)] = label
    except Exception as exc:
        logger.warning("Could not read manual labels: %s", exc)
    return result


def _training_matrix(rows):
    manual = _load_manual_labels()
    flare_tree = _load_external_flare_tree()
    X, y, ids, coords, label_sources = [], [], [], [], []

    for row in rows:
        event_id = int(row["id"])
        if event_id in manual:
            label = manual[event_id]
            source = "MANUAL_REVIEW"
        elif _is_known_flare(row, flare_tree):
            label = "GAS FLARE / INDUSTRIAL THERMAL SOURCE"
            source = "NASA_ORNL_VIIRS_NIGHTFIRE"
        else:
            label, confidence = _weak_label(row)
            if confidence < 0.58:
                continue
            source = "WEAK_EVIDENCE_BOOTSTRAP"

        X.append(_row_features(row))
        y.append(CLASSES.index(label))
        ids.append(event_id)
        coords.append((
            _safe_float(row.get("latitude")),
            _safe_float(row.get("longitude")),
        ))
        label_sources.append(source)

    return (
        np.asarray(X, dtype=np.float32),
        np.asarray(y, dtype=np.int64),
        ids,
        coords,
        label_sources,
    )


def _source_signature():
    query = text(
        """
        SELECT COUNT(*) AS event_count,
               COALESCE(MAX(updated_at), TIMESTAMPTZ 'epoch') AS max_updated
        FROM processed.thermal_events
        """
    )
    with engine.connect() as conn:
        row = conn.execute(query).mappings().one()
    return int(row["event_count"]), row["max_updated"]


def _registry_row():
    with engine.connect() as conn:
        return conn.execute(
            text("""
                SELECT model_name, model_version, trained_on_events,
                       source_max_updated_at, training_data_signature, updated_at
                FROM processed.ml_model_registry
                WHERE model_name = :name
            """),
            {"name": MODEL_NAME},
        ).mappings().first()


def _training_data_signature():
    parts = []
    if LABELS_PATH.exists():
        parts.append(f"labels:{LABELS_PATH.stat().st_mtime_ns}:{LABELS_PATH.stat().st_size}")
    for path in sorted(EXTERNAL_FLARE_DIR.rglob("*.csv")) if EXTERNAL_FLARE_DIR.exists() else []:
        try:
            stat = path.stat()
            parts.append(f"flare:{path.name}:{stat.st_mtime_ns}:{stat.st_size}")
        except OSError:
            continue
    return "|".join(parts)[:160] or "NO_EXTERNAL_LABEL_DATA"


def _needs_retrain(event_count, max_updated, training_data_signature):
    row = _registry_row()
    if row is None:
        return True
    return (
        int(row["trained_on_events"] or 0) != event_count
        or row["source_max_updated_at"] != max_updated
        or str(row["training_data_signature"] or "") != training_data_signature
        or not MODEL_PATH.exists()
    )


def _load_model():
    if not MODEL_PATH.exists():
        return None
    model = XGBClassifier()
    model.load_model(str(MODEL_PATH))
    return model


def _persist_scores(rows, model, trained_count, label_source, active_classes):
    X = np.asarray([_row_features(r) for r in rows], dtype=np.float32)
    probabilities = model.predict_proba(X)
    local_predictions = np.asarray(model.predict(X)).reshape(-1).astype(int)
    now = datetime.now(timezone.utc)

    with engine.begin() as conn:
        for row, local_pred, probs in zip(rows, local_predictions, probabilities):
            probs_list = [float(v) for v in probs]
            confidence = float(max(probs_list)) if probs_list else 0.0
            global_pred = active_classes[int(local_pred)]
            global_probs = {
                CLASSES[global_index]: round(float(probs[local_index]), 6)
                for local_index, global_index in enumerate(active_classes)
            }
            conn.execute(
                text("""
                    INSERT INTO processed.event_ml_scores (
                        event_id, model_name, model_version,
                        anomaly_score, normality_score,
                        trained_on_events, predicted_class,
                        classification_confidence, class_probabilities,
                        training_label_source, feature_version, updated_at
                    )
                    VALUES (
                        :event_id, :model_name, :model_version,
                        0, 0, :trained_on_events, :predicted_class,
                        :classification_confidence, CAST(:class_probabilities AS jsonb),
                        :training_label_source, :feature_version, :updated_at
                    )
                    ON CONFLICT (event_id) DO UPDATE SET
                        model_name = EXCLUDED.model_name,
                        model_version = EXCLUDED.model_version,
                        trained_on_events = EXCLUDED.trained_on_events,
                        predicted_class = EXCLUDED.predicted_class,
                        classification_confidence = EXCLUDED.classification_confidence,
                        class_probabilities = EXCLUDED.class_probabilities,
                        training_label_source = EXCLUDED.training_label_source,
                        feature_version = EXCLUDED.feature_version,
                        updated_at = EXCLUDED.updated_at
                """),
                {
                    "event_id": int(row["id"]),
                    "model_name": MODEL_NAME,
                    "model_version": MODEL_VERSION,
                    "trained_on_events": int(trained_count),
                    "predicted_class": CLASSES[int(global_pred)],
                    "classification_confidence": round(confidence, 4),
                    "class_probabilities": json.dumps(
                        global_probs,
                        separators=(",", ":"),
                    ),
                    "training_label_source": label_source,
                    "feature_version": FEATURE_VERSION,
                    "updated_at": now,
                },
            )


def train_or_refresh_ml_model(force=False):
    event_count, source_max_updated_at = _source_signature()
    training_data_signature = _training_data_signature()
    if event_count < MIN_TRAINING_EVENTS:
        return {"status": "waiting", "events": event_count, "model": MODEL_NAME}

    if not force and not _needs_retrain(event_count, source_max_updated_at, training_data_signature):
        return {
            "status": "unchanged",
            "events": event_count,
            "model": MODEL_NAME,
            "version": MODEL_VERSION,
        }

    rows = _fetch_rows()
    X, y, ids, coords, label_sources = _training_matrix(rows)
    if len(y) < MIN_TRAINING_EVENTS:
        return {"status": "waiting", "events": len(y), "model": MODEL_NAME}

    counts = np.bincount(y, minlength=len(CLASSES))
    active_classes = [i for i, c in enumerate(counts) if c >= MIN_CLASS_SAMPLES]
    if len(active_classes) < 2:
        return {
            "status": "waiting",
            "events": len(y),
            "reason": "Need at least two classes with five examples each.",
        }

    keep = np.isin(y, active_classes)
    X, y = X[keep], y[keep]
    ids = [v for v, k in zip(ids, keep) if k]
    coords = [v for v, k in zip(coords, keep) if k]
    label_sources = [v for v, k in zip(label_sources, keep) if k]
    active_classes = list(active_classes)
    global_to_local = {global_index: local_index for local_index, global_index in enumerate(active_classes)}
    y_local = np.asarray([global_to_local[int(label)] for label in y], dtype=np.int64)

    # Geographic holdout: quantize India/global coordinates into coarse cells
    # and use cells as groups when enough unique cells exist. This avoids a
    # misleading random split of nearby hotspots.
    groups = np.array([
        f"{math.floor(lat / 0.5)}:{math.floor(lon / 0.5)}"
        for lat, lon in coords
    ])
    unique_groups = np.unique(groups)
    if len(unique_groups) >= 6:
        test_groups = set(unique_groups[::5])
        test_mask = np.array([g in test_groups for g in groups])
        if test_mask.sum() < max(10, int(len(y) * .1)):
            _, test_idx = train_test_split(
                np.arange(len(y)), test_size=.2, random_state=42, stratify=y_local
            )
            test_mask = np.zeros(len(y), dtype=bool)
            test_mask[test_idx] = True
    else:
        idx = np.arange(len(y))
        _, test_idx = train_test_split(
            idx, test_size=.2, random_state=42, stratify=y_local
        )
        test_mask = np.zeros(len(y), dtype=bool)
        test_mask[test_idx] = True

    train_mask = ~test_mask
    if len(np.unique(y_local[train_mask])) < 2:
        train_mask = np.ones(len(y_local), dtype=bool)
        test_mask = np.zeros(len(y_local), dtype=bool)

    model = XGBClassifier(
        objective="multi:softprob",
        num_class=len(active_classes),
        n_estimators=320,
        max_depth=6,
        learning_rate=0.05,
        subsample=0.90,
        colsample_bytree=0.90,
        reg_lambda=1.5,
        reg_alpha=0.1,
        min_child_weight=2,
        tree_method="hist",
        eval_metric="mlogloss",
        random_state=42,
        n_jobs=4,
    )
    model.fit(
        X[train_mask],
        y_local[train_mask],
        sample_weight=np.asarray([
            1.0 / max(counts[active_classes[int(label)]], 1) ** 0.5
            for label in y_local[train_mask]
        ], dtype=np.float32),
    )

    if test_mask.sum() > 0:
        pred_local = model.predict(X[test_mask]).astype(int)
        pred_global = np.asarray([active_classes[int(v)] for v in pred_local], dtype=np.int64)
        y_global_test = y[test_mask]
        metrics = {
            "holdout_accuracy": round(float(accuracy_score(y_global_test, pred_global)), 4),
            "holdout_balanced_accuracy": round(
                float(balanced_accuracy_score(y_global_test, pred_global)), 4
            ),
            "holdout_macro_f1": round(
                float(f1_score(y_global_test, pred_global, labels=active_classes, average="macro", zero_division=0)), 4
            ),
            "holdout_samples": int(test_mask.sum()),
        }
    else:
        metrics = {"holdout_samples": 0}

    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    model.save_model(str(MODEL_PATH))
    with METRICS_PATH.open("w", encoding="utf-8") as f:
        json.dump({
            "model_name": MODEL_NAME,
            "model_version": MODEL_VERSION,
            "feature_version": FEATURE_VERSION,
            "label_strategy": "manual labels when supplied, otherwise weak evidence bootstrap",
            "metrics_are_not_ground_truth": True,
            "metrics": metrics,
            "class_counts": {
                CLASSES[i]: int(counts[i]) for i in range(len(CLASSES))
            },
            "active_classes": [CLASSES[i] for i in active_classes],
            "trained_examples": int(len(y)),
            "generated_at": datetime.now(timezone.utc).isoformat(),
        }, f, indent=2)

    _persist_scores(rows, model, len(y), "MANUAL_REVIEW_OR_WEAK_BOOTSTRAP", active_classes)
    now = datetime.now(timezone.utc)
    with engine.begin() as conn:
        conn.execute(
            text("""
                INSERT INTO processed.ml_model_registry (
                    model_name, model_version, trained_on_events,
                    source_max_updated_at, training_data_signature, updated_at
                )
                VALUES (:name, :version, :count, :source_time, :training_signature, :updated)
                ON CONFLICT (model_name) DO UPDATE SET
                    model_version = EXCLUDED.model_version,
                    trained_on_events = EXCLUDED.trained_on_events,
                    source_max_updated_at = EXCLUDED.source_max_updated_at,
                    training_data_signature = EXCLUDED.training_data_signature,
                    updated_at = EXCLUDED.updated_at
            """),
            {
                "name": MODEL_NAME,
                "version": MODEL_VERSION,
                "count": int(event_count),
                "source_time": source_max_updated_at,
                "training_signature": training_data_signature,
                "updated": now,
            },
        )

    logger.info(
        "XGBoost classifier trained: events=%s examples=%s metrics=%s",
        event_count, len(y), metrics,
    )
    return {
        "status": "trained",
        "model": MODEL_NAME,
        "version": MODEL_VERSION,
        "events": event_count,
        "training_examples": len(y),
        "metrics": metrics,
    }


def get_ml_classification(event_id):
    query = text("""
        SELECT predicted_class, classification_confidence, class_probabilities,
               model_name, model_version, trained_on_events,
               training_label_source, feature_version, updated_at
        FROM processed.event_ml_scores
        WHERE event_id = :event_id
    """)
    with engine.connect() as conn:
        row = conn.execute(query, {"event_id": event_id}).mappings().first()

    # Self-heal rows written by the pre-1.1 classifier. XGBoost is a
    # multiclass classifier, so a zero confidence is not a meaningful scored
    # result. The next request/pipeline run refreshes those rows automatically.
    needs_refresh = (
        row is None
        or not row["predicted_class"]
        or str(row["model_version"] or "") != MODEL_VERSION
        or float(row["classification_confidence"] or 0.0) <= 0.0
    )
    if needs_refresh:
        try:
            train_or_refresh_ml_model()
            with engine.connect() as conn:
                row = conn.execute(query, {"event_id": event_id}).mappings().first()
        except Exception as exc:
            logger.warning("Unable to refresh XGBoost score for event %s: %s", event_id, exc)

    if not row or not row["predicted_class"]:
        return None
    probs = row["class_probabilities"] or {}
    if isinstance(probs, str):
        try:
            probs = json.loads(probs)
        except Exception:
            probs = {}
    return {
        "classification": row["predicted_class"],
        "classification_confidence": float(row["classification_confidence"] or 0),
        "class_probabilities": probs,
        "model_name": row["model_name"],
        "model_version": row["model_version"],
        "trained_on_events": int(row["trained_on_events"] or 0),
        "training_label_source": row["training_label_source"],
        "feature_version": row["feature_version"],
        "updated_at": row["updated_at"].isoformat() if row["updated_at"] else None,
    }


def get_ml_score(event_id):
    """Backward-compatible alias used by older API code."""
    result = get_ml_classification(event_id)
    if not result:
        return None
    return {
        "anomaly_score": 0.0,
        "normality_score": 0.0,
        "predicted_class": result["classification"],
        "classification": result["classification"],
        "model_name": result["model_name"],
        "model_version": result["model_version"],
        "trained_on_events": result["trained_on_events"],
        "updated_at": result["updated_at"],
        "classification": result["classification"],
        "classification_confidence": result["classification_confidence"],
        "class_probabilities": result["class_probabilities"],
    }


def get_ml_summary():
    row = _registry_row()
    if not row:
        return None
    metrics = {}
    if METRICS_PATH.exists():
        try:
            metrics = json.loads(METRICS_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {
        "model_name": row["model_name"],
        "model_version": row["model_version"],
        "trained_on_events": int(row["trained_on_events"]),
        "source_max_updated_at": (
            row["source_max_updated_at"].isoformat()
            if row["source_max_updated_at"] else None
        ),
        "training_data_signature": row.get("training_data_signature"),
        "updated_at": row["updated_at"].isoformat() if row["updated_at"] else None,
        "metrics": metrics.get("metrics", {}),
        "metrics_are_not_ground_truth": True,
    }
