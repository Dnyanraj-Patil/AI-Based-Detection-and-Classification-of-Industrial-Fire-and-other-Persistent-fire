"""XGBoost source-classification layer for ThermoIntel.

The model is a tabular multiclass classifier over FIRMS + PostGIS/WorldCover
features.  Because ThermoIntel does not ship with a verified fire-cause
ground-truth corpus, the default bootstrap labels are generated by the
existing explainable evidence classifier.  If data/ml_labels.csv contains
reviewed labels, those labels are preferred.

This makes XGBoost the ML classifier without pretending that weak labels are
ground truth.  The deterministic evidence rules remain as safety/context
guardrails and as the bootstrap teacher until reviewed labels are available.
"""
