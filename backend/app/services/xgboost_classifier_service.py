def _safe_float(v, default=0.0):
    try:
        if v is None:
            return default
        x = float(v)
        return x if math.isfinite(x) else default
    except (TypeError, ValueError):
        return default


def _safe_int(v, default=0):
    try:
        return int(v or 0)
    except (TypeError, ValueError):
        return default


def _norm_text(*values):
    return " ".join(str(v or "").lower() for v in values)


def _contains(text_value, terms):
    value = str(text_value or "").lower()
    return any(term in value for term in terms)


def _fetch_rows():
    query = text(
        """
        SELECT
            e.id,
            e.first_detected_at,
            e.max_frp,
            e.average_frp,
            e.max_bright_ti4,
            e.average_bright_ti4,
            e.detection_count,
            e.observation_duration_minutes,
            e.centroid_latitude AS latitude,
            e.centroid_longitude AS longitude,
            COALESCE(c.nearest_facility_distance_meters, 999999.0)
                AS facility_distance,
            COALESCE(c.facilities_within_1km, 0) AS facilities_within_1km,
            COALESCE(c.facilities_within_5km, 0) AS facilities_within_5km,
            COALESCE(c.is_inside_industrial_area, FALSE) AS inside_industrial,
            COALESCE(c.nearest_facility_type, '') AS facility_type,
            COALESCE(c.nearest_industrial_type, '') AS industrial_type,
            COALESCE(lc.land_cover_class, 'UNKNOWN') AS land_cover_class,
            COALESCE(lc.land_cover_confidence, 0) AS land_cover_confidence
        FROM processed.thermal_events e
        LEFT JOIN processed.event_industrial_context c
            ON c.event_id = e.id
        LEFT JOIN processed.event_land_cover lc
            ON lc.event_id = e.id
        WHERE e.max_frp IS NOT NULL
           OR e.max_bright_ti4 IS NOT NULL
        ORDER BY e.id
        """
    )
    with engine.connect() as conn:
        return [dict(r) for r in conn.execute(query).mappings().all()]


